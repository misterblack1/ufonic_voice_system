#!/usr/bin/env python3
"""Generate words.inc for spell.asm from the snspellua labels and card image.

Usage: python mkwords.py card.bin [out.inc]
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LABELS = os.path.join(HERE, '..', 'speech', 'snspellua.csv')

FIRST_WORD = 65
LAST_WORD = 304
DROPPED = {118, 165}

# Fixed phrases the game names, with the label text each must carry.
FIXED = [
    ('PH_TRYAGAIN', 1, 'try again'),
    ('PH_CORRECTSP', 2, 'the correct spelling of'),
    ('PH_IS', 3, 'is'),
    ('PH_CORRECT', 6, 'correct'),
    ('PH_A', 7, 'a'),
    ('PH_Z', 32, 'z'),
    ('PH_TONE', 33, None),
    ('PH_ZERO', 34, '0'),
    ('PH_TEN', 44, '10'),
    ('PH_THISCORRECT', 45, 'this is correct'),
    ('PH_YOURIGHT', 48, 'you are right'),
    ('PH_WRONG', 49, 'wrong'),
    ('PH_INCORRECT', 50, 'that is incorrect'),
    ('PH_SPELL', 51, 'spell'),
    ('PH_NOWSPELL', 52, 'now spell'),
    ('PH_NEXTSPELL', 53, 'next spell'),
    ('PH_NOWTRY', 54, 'now try'),
    ('PH_TRY', 55, 'try'),
    ('PH_SAYIT', 56, 'say it'),
    ('PH_IWIN', 57, 'i win'),
    ('PH_YOUWIN', 58, 'you win'),
    ('PH_YOURSCORE', 59, 'here is your score'),
    ('PH_PERFECT', 60, 'perfect score'),
    ('PH_JINGLE1', 61, None),
    ('PH_JINGLE2', 62, None),
    ('PH_JINGLE3', 63, None),
    ('PH_JINGLE4', 64, None),
]

# Captions for numbers read better spelled out.
NUMBERS = ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN',
           'EIGHT', 'NINE', 'TEN']


def fail(msg):
    sys.exit('mkwords: ' + msg)


def text_bytes(s):
    return ','.join('$%02X' % (ord(c) | 0x80) for c in s) + ',0' if s else '0'


def main():
    if len(sys.argv) < 2:
        fail('usage: mkwords.py card.bin [out.inc]')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, 'words.inc')
    rows = {}
    for r in csv.DictReader(open(LABELS, newline='')):
        if r['index']:
            rows[int(r['index'])] = r

    for name, idx, want in FIXED:
        r = rows.get(idx)
        if r is None:
            fail('phrase %d missing' % idx)
        if want is not None and (r['status'] != 'OK' or r['heard'] != want):
            fail('phrase %d is %r %r, expected %r' % (idx, r['status'], r['heard'], want))
    for idx in range(7, 33):
        if rows[idx]['heard'] != chr(ord('a') + idx - 7):
            fail('letter phrase %d is %r' % (idx, rows[idx]['heard']))

    words = []
    for idx in range(FIRST_WORD, LAST_WORD + 1):
        if idx in DROPPED:
            continue
        r = rows.get(idx)
        if r is None or r['status'] != 'OK':
            fail('word phrase %d not OK' % idx)
        w = r['heard'].upper()
        if not w.isalpha() or not w.isascii():
            fail('word phrase %d is %r' % (idx, r['heard']))
        words.append((idx, w))

    caps = []
    for idx in range(LAST_WORD + 1):
        r = rows.get(idx)
        if idx == 0 or r is None or r['status'] != 'OK' or idx in DROPPED:
            caps.append('')
        elif 34 <= idx <= 44:
            caps.append(NUMBERS[idx - 34])
        else:
            caps.append(r['heard'].upper())

    card = open(sys.argv[1], 'rb').read()
    if len(card) != 65536:
        fail('card image is %d bytes' % len(card))
    cardsum = sum(card) & 0xFFFF

    L = ['; Generated by mkwords.py from snspellua.csv and snspellua.bin. Do not edit.', '']
    L.append('NWORDS = %d' % len(words))
    L.append('MAXPHRASE = %d' % LAST_WORD)
    L.append('CARDSUM = $%04X' % cardsum)
    L.append('MAXLEN = %d' % max(len(w) for _, w in words))
    for name, idx, _ in FIXED:
        L.append('%s = %d' % (name, idx))
    L.append('')
    for tag, sel in (('word_ph_lo', lambda i: i & 0xFF), ('word_ph_hi', lambda i: i >> 8)):
        L.append(tag)
        for k in range(0, len(words), 16):
            L.append('    !byte ' + ','.join('$%02X' % sel(i) for i, _ in words[k:k + 16]))
    L.append('')
    L.append('; Caption pointer for each phrase index, 0 to MAXPHRASE')
    L.append('cap_tab')
    for k in range(0, len(caps), 8):
        L.append('    !word ' + ','.join('cap_%d' % i for i in range(k, min(k + 8, len(caps)))))
    for i, c in enumerate(caps):
        L.append('cap_%d !byte %s' % (i, text_bytes(c)))
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print('mkwords: %d words, card sum $%04X, wrote %s' % (len(words), cardsum, out))


if __name__ == '__main__':
    main()
